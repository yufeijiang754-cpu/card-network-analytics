"""Data access + shared chart styling for the Streamlit dashboard.

The dashboard reads the DuckDB warehouse produced by dbt in read-only mode. To point it at
Snowflake instead, replace `query()` with a snowflake.connector / Snowpark session call;
every page only uses `query()` and the schema names (marts, dq, dq_audit).
"""

from __future__ import annotations

import os
from pathlib import Path

import duckdb
import pandas as pd
import plotly.graph_objects as go
import plotly.io as pio
import streamlit as st

ROOT = Path(__file__).resolve().parents[1]
DB_PATH = Path(os.environ.get("DUCKDB_PATH", ROOT / "warehouse" / "payments.duckdb"))

# Reference data-viz palette: categorical slots in FIXED order (colour follows the entity).
SERIES = ["#2a78d6", "#eb6834", "#1baf7a", "#eda100", "#e87ba4", "#008300", "#4a3aa7", "#e34948"]
STATUS = {"good": "#0ca30c", "warning": "#fab219", "serious": "#ec835a", "critical": "#d03b3b"}
INK, INK_2, MUTED, GRID, AXIS = "#0b0b0b", "#52514e", "#898781", "#e1e0d9", "#c3c2b7"
SURFACE = "#fcfcfb"

# Stable colour per entity, so filtering never repaints a series.
CHANNEL_COLORS = {"card_present": SERIES[0], "card_not_present": SERIES[1]}
DIMENSION_COLORS = {"completeness": SERIES[0], "uniqueness": SERIES[1], "validity": SERIES[2],
                    "timeliness": SERIES[3], "referential_integrity": SERIES[4], "consistency": SERIES[5]}

pio.templates["network"] = go.layout.Template(
    layout=dict(
        font=dict(family="system-ui, -apple-system, Segoe UI, sans-serif", color=INK_2, size=12),
        paper_bgcolor=SURFACE, plot_bgcolor=SURFACE, colorway=SERIES,
        xaxis=dict(gridcolor=GRID, linecolor=AXIS, zeroline=False, ticks="", showgrid=False),
        yaxis=dict(gridcolor=GRID, linecolor=AXIS, zeroline=False, ticks=""),
        hoverlabel=dict(bgcolor="white", font_color=INK, bordercolor=GRID),
        legend=dict(orientation="h", yanchor="bottom", y=1.02, x=0, title_text=""),
        margin=dict(l=8, r=8, t=40, b=8), bargap=0.25,
    )
)
pio.templates.default = "network"


@st.cache_resource
def _connection() -> duckdb.DuckDBPyConnection:
    if not DB_PATH.exists():
        st.error(f"Warehouse not found at `{DB_PATH}`. Run `./run_all.sh` (or `make build`) first.")
        st.stop()
    return duckdb.connect(str(DB_PATH), read_only=True)


@st.cache_data(ttl=600, show_spinner=False)
def query(sql: str, params: tuple = ()) -> pd.DataFrame:
    return _connection().execute(sql, list(params)).df()


def table_exists(schema: str, table: str) -> bool:
    return bool(query("select count(*) as n from information_schema.tables where table_schema = ? and table_name = ?",
                      (schema, table)).n.iat[0])


def style(fig: go.Figure, title: str, height: int = 320) -> go.Figure:
    fig.update_layout(
        template="network", plot_bgcolor=SURFACE, paper_bgcolor=SURFACE,
        title=dict(text=title, font=dict(size=14, color=INK), x=0, xanchor="left", y=0.98, yanchor="top"),
        legend=dict(orientation="h", yanchor="bottom", y=1.01, x=0, title_text=""),
        margin=dict(l=8, r=24, t=72, b=8), height=height)
    fig.update_xaxes(automargin=True, gridcolor=GRID, linecolor=AXIS, title_font_color=INK_2)
    fig.update_yaxes(automargin=True, gridcolor=GRID, linecolor=AXIS, title_font_color=INK_2)
    fig.update_traces(selector=dict(type="scatter"), line_width=2)
    fig.update_traces(selector=dict(type="bar"), marker_line_width=0)
    return fig


def synthetic_banner() -> None:
    st.caption("All data is **synthetic** (generated by `generator/`). It is not real payment data.")
